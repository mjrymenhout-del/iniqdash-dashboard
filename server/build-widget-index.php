declare(strict_types=1);

/**
 * Default widget index — php server/build-widget-index.php [--check]
 *
 * Validates every FACTORY widget package (widgets/default/<id>/widget.json, see server/WidgetPackages.php) and writes
 * widgets/index.js: their manifests as one JavaScript list, loaded by the pages before the widget registry.
 * This is a release-time step for the factory widgets only (the editor also runs from a local file in demo mode,
 * where a browser cannot read widget.json).
 *
 * CUSTOM widgets (widgets/custom/<folder>/) are NOT in this index: the server discovers them on every editor page
 * load (gate.php), so installing one is copying its folder — no build step.
 * --check only reports whether widgets/index.js is up to date.
 */

require __DIR__ . '/WidgetPackages.php';

$root = dirname(__DIR__);
$check = in_array('--check', $argv, true);
$scan = WidgetPackages::scan($root, 'default');
if ($scan['errors']) {
    fwrite(STDERR, "Widget packages have errors:\n  " . implode("\n  ", array_map(static fn ($e) => "{$e['folder']}widget.json: {$e['error']}", $scan['errors'])) . "\n");
    exit(1);
}
// the content version is for custom packages (cache busting at run time); the factory index stays stable
$out = array_map(static function ($m) { unset($m['v']); return $m; }, $scan['packages']);
$js = "/* This Source Code Form is subject to the terms of the Mozilla Public\n"
    . " * License, v. 2.0. If a copy of the MPL was not distributed with this\n"
    . " * file, You can obtain one at http://mozilla.org/MPL/2.0/.\n"
    . " * Copyright © 2026 Marcel Rymenhout and IniqDash contributors */\n"
    . "/* GENERATED by server/build-widget-index.php from every widgets/default/<id>/widget.json — do not edit by hand.\n"
    . "   Factory widget package manifests, read by the widget registry (components/editor/registry.js).\n"
    . "   Custom widgets (widgets/custom/) are discovered by the server at page load and are not listed here. */\n"
    . 'window.IniqWidgetPackages = ' . json_encode($out, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ";\n";
$target = "$root/widgets/index.js";
if ($check) {
    $same = is_file($target) && file_get_contents($target) === $js;
    echo $same ? "widgets/index.js is up to date (" . count($out) . " packages)\n" : "widgets/index.js is OUT OF DATE — run php server/build-widget-index.php\n";
    exit($same ? 0 : 1);
}
file_put_contents($target, $js);
echo 'widgets/index.js written: ' . count($out) . " packages\n";
